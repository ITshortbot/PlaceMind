const { chromium } = require('@playwright/test');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.goto('http://localhost:3000/resume', { waitUntil: 'networkidle', timeout: 60000 });
  await page.fill('[placeholder="Your name"]', 'Alex Doe');
  await page.fill('[placeholder="e.g. Backend Engineer"]', 'Backend Engineer');
  await page.fill('[placeholder="you@example.com"]', 'alex.doe@example.com');
  await page.fill('[placeholder="Optional"]', '+91 90000 00000');
  await page.fill('[placeholder="2-3 sentences about your experience"]', 'Backend engineer with 3 years building Python APIs and data pipelines.');
  await page.fill('[placeholder="Python, FastAPI, PostgreSQL"]', 'Python, FastAPI, PostgreSQL, Redis, Docker');
  await page.fill('[placeholder="Employer name"]', 'ExampleCorp');
  await page.fill('[placeholder*="Built FastAPI services"]', 'Built FastAPI services serving 2M requests/day\nCut p95 latency from 800ms to 240ms\nLed migration to event-driven pipeline processing 50k events/min\nMentored 3 junior engineers on API design and testing');
  await page.fill('[placeholder="e.g. B.Tech Computer Science"]', 'B.Tech Computer Science');
  await page.fill('[placeholder="University name"]', 'Example University');
  await page.fill('[placeholder="e.g. 2023"]', '2023');
  await page.waitForTimeout(1500);
  await page.screenshot({ path: '/workspaces/PlaceMind/frontend/public/print-screen.png' });
  await page.emulateMedia({ media: 'print' });
  await page.pdf({ path: '/workspaces/PlaceMind/frontend/public/print-check.pdf', format: 'A4', printBackground: true, preferCSSPageSize: true });
  await browser.close();
  const fs = require('fs');
  const buf = fs.readFileSync('/workspaces/PlaceMind/frontend/public/print-check.pdf');
  const s = buf.toString('latin1');
  const m = s.match(/\/Count\s+(\d+)/);
  const mb = s.match(/\/MediaBox\s*\[([^\]]*)\]/);
  console.log('PDF_BYTES=' + buf.length);
  console.log('PDF_PAGES=' + (m ? m[1] : 'unknown'));
  console.log('MEDIABOX=' + (mb ? mb[1].trim() : 'unknown'));
  console.log('PDF_CHECK_DONE');
})().catch(e => { console.error('PDF_CHECK_FAIL', e.message); process.exit(1); });
